// جدول الأنماط الرسمي: 107 رمز، كل واحد 3 بارات و3 فراغات بعرض 1–4 (11 module)، والـstop 13.
var C128 = ['212222','222122','222221','121223','121322','131222','122213','122312','132212','221213','221312','231212','112232','122132','122231','113222','123122','123221','223211','221132','221231','213212','223112','312131','311222','321122','321221','312212','322112','322211','212123','212321','232121','111323','131123','131321','112313','132113','132311','211313','231113','231311','112133','112331','132131','113123','113321','133121','313121','211331','231131','213113','213311','213131','311123','311321','331121','312113','312311','332111','314111','221411','431111','111224','111422','121124','121421','141122','141221','112214','112412','122114','122411','142112','142211','241211','221114','413111','241112','134111','111242','121142','121241','114212','124112','124211','411212','421112','421211','212141','214121','412121','111143','111341','131141','114113','114311','411113','411311','113141','114131','311141','411131','211412','211214','211232','2331112'];
var START_B = 104, START_C = 105, CODE_B = 100, CODE_C = 99, STOP = 106;

// نفس منطق python-barcode (اللي اتعمل بيه النموذج المعتمد): يبدأ C لو أول 4+ أرقام،
// ويبدّل لـC عند أي 4 أرقام متتالية زوجية، ويرجع B لأي حرف غير رقمي.
export function code128Values(text){
  var s = String(text || '');
  var vals = [], i = 0, set;
  function digitsAhead(k){ var n = 0; while(k + n < s.length && s.charCodeAt(k + n) >= 48 && s.charCodeAt(k + n) <= 57) n++; return n; }
  if(digitsAhead(0) >= 4){ set = 'C'; vals.push(START_C); } else { set = 'B'; vals.push(START_B); }
  while(i < s.length){
    var d = digitsAhead(i);
    if(set === 'C'){
      if(d >= 2){ vals.push(parseInt(s.substr(i, 2), 10)); i += 2; continue; }
      set = 'B'; vals.push(CODE_B); continue;
    }
    // set B
    if(d >= 4){ set = 'C'; vals.push(CODE_C); continue; }
    var ch = s.charCodeAt(i);
    if(ch < 32 || ch > 127) throw new Error('code128: حرف مش مدعوم في subset B: ' + s[i]);
    vals.push(ch - 32); i++;
  }
  var sum = vals[0];
  for(var k = 1; k < vals.length; k++) sum += vals[k] * k;
  vals.push(sum % 103);
  vals.push(STOP);
  return vals;
}

// نمط البارات كسلسلة '1'/'0' (زي python-barcode build()[0]) — للمعايرة ضد بايثون
export function code128Modules(text){
  var out = '';
  code128Values(text).forEach(function(v){
    var p = C128[v];
    for(var j = 0; j < p.length; j++){ var w = +p[j]; out += (j % 2 === 0 ? '1' : '0').repeat(w); }
  });
  return out;   // نمط الـstop (2331112) شامل بار الإنهاء — 13 module
}

