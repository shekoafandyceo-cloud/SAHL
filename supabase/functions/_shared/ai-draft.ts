const cairoDay = (iso: string) => new Intl.DateTimeFormat("en-CA", { timeZone: "Africa/Cairo" }).format(new Date(iso));
/** الحالة + «خرج النهارده/إمبارح» للأوردر اللي مع المندوب (17 نوفمبر — العميل اللي عايزه النهارده يتقاله «النهارده» بس لو خرج النهارده فعلاً). */
/** 23 نوفمبر: علامة «مع شركة الشحن» جنب الحالة (القاعدة 22(ل) بتشاور عليها بالنص ده) — بتتحط بس لما o.fee_tag. */
export const FEE_TAG_TEXT = " (مع شركة الشحن — الإلغاء دلوقتي برسوم)";
export function statusText(o: OrderLite, nowIso: string): string {
  const base = statusLabel(o.status);
  if (o.status === "cancelled" && o.cancel_tag === "self") return base + " (العميل لغاه من الواتساب من أقل من يومين — ينفع يتفعّل تاني)";
  if (o.status === "cancelled" && o.cancel_tag === "staff") return base + " (اتلغى من أقل من يومين — تفعيله بإيد موظف)";
  const fee = o.fee_tag ? FEE_TAG_TEXT : "";
  if (o.status !== "Out for delivery" || !o.status_at) return base + fee;
  const d = Math.round((Date.parse(cairoDay(nowIso)) - Date.parse(cairoDay(o.status_at))) / 86400000);
  if (!isFinite(d) || d < 0) return base + fee;
  return base + (d === 0 ? " (خرج النهارده)" : d === 1 ? " (خرج إمبارح ولسه مااتسلّمش)" : " (خرج من " + d + " يوم ولسه مااتسلّمش)") + fee;
}

// ── الرسايل اللي مش نص: قرار ثابت من غير موديل ──────────────────────
/** null = كمّل للموديل. غير كده مسودة جاهزة (أو skip).
 *  media = اللي السيستم فهمه من الفويس/الصورة (ai-media.ts) — موجود = الموديل يرد عليها زي الكلام · مش موجود (فشل/قديم) = القرار الثابت القديم بالحرف. */
export function preRule(type: string, body: string | null | undefined, media?: string | null): Draft | null {
  const t = String(type || "text");
  const hasText = !!String(body || "").trim();
  if (t === "text" || t === "interactive") return hasText ? null : { behavior: "skip", intent: "رسالة فاضية", reply: "", card: "", note: "" };
  if (t === "button" || t === "reaction" || t === "sticker" || t === "unsupported")
    return { behavior: "skip", intent: "ضغطة زرار/تفاعل", reply: "", card: "", note: "" };
  if ((t === "audio" || t === "voice" || t === "image") && String(media || "").trim()) return null;
  if (t === "audio" || t === "voice")
    return { behavior: "escalate", intent: "رسالة صوتية", reply: "", card: "", note: "رسالة صوتية — محتاجة زميل يسمعها ويرد." };
  if (t === "image" && hasText) return null; // الكابشن يتعامل كنص
  if (t === "image")
    return { behavior: "clarify", intent: "صورة من غير نص", reply: "ممكن حضرتك توضح المطلوب يا فندم؟", card: "", note: "صورة من غير نص — المساعد مابيشوفش الصور، راجعها قبل الإرسال." };
  return { behavior: "escalate", intent: "ميديا (" + t + ")", reply: "", card: "", note: "رسالة " + t + " — محتاجة زميل يشوفها." };
}

