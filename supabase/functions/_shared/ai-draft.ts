/** 23 نوفمبر — رسوم الإلغاء بعد الشحن شغّالة: نفس الـschema + fee (enum قصير قبل order — order آخر حاجة زي ما هو). مش required:
 *  الموديل لو ماكتبوش = مفيش حدث (وطلب الرسوم نفسه بيتعرف برضه من رقم التحويل في الرد — ai-fee.ts replyAsksFee). */
export const FEE_VALUES = ["none", "request", "paid", "refused", "keep"] as const;
export const RESPONSE_SCHEMA_FEE = {
  ...RESPONSE_SCHEMA,
  properties: { ...RESPONSE_SCHEMA.properties, fee: { type: "STRING", enum: [...FEE_VALUES] } },
  propertyOrdering: ["behavior", "intent", "reply", "card", "note", "reactivate", "fee", "order"],
};

/** order من خرج الموديل: في collect بس، ولازم فيه منتج واسم وعنوان (غير كده = لسه بيجمّع → null ورد الموديل هو اللي يتبعت). */
export function parseOrder(behavior: string, raw: unknown): DraftOrder | null {
  if (behavior !== "collect" || !raw || typeof raw !== "object" || Array.isArray(raw)) return null;
  const r = raw as Record<string, unknown>;
  const t = (k: string, n: number) => String(r[k] ?? "").replace(/[\r\n]+/g, " ").replace(/\s+/g, " ").trim().slice(0, n);
  const product = t("product", 120), name = t("name", 80), address = t("address", 300);
  if (!product || !name || !address) return null;
  const q = Math.trunc(Number(r.qty));
  return { product, variant: t("variant", 60), qty: isFinite(q) && q >= 1 ? q : 1, name, phone: t("phone", 40), governorate: t("governorate", 40), address };
}

/** بيحوّل نص الموديل لمسودة سليمة. null لو مش JSON أو behavior مش معروف. card لازم يطابق كارت موجود وإلا بيتشال. */
export function parseDraft(text: string, cards: CardLite[]): Draft | null {
  let raw = String(text || "").trim();
  const fence = raw.match(/```(?:json)?\s*([\s\S]*?)```/);
  if (fence) raw = fence[1].trim();
  let o: Record<string, unknown>;
  try { o = JSON.parse(raw); } catch { return null; }
  if (!o || typeof o !== "object") return null;
  const behavior = String(o.behavior || "") as Behavior;
  if (!BEHAVIORS.includes(behavior)) return null;
  let reply = String(o.reply ?? "").replace(/\r/g, "").trim();
  if (reply.length > 1500) reply = reply.slice(0, 1500);
  const wanted = String(o.card ?? "").replace(/[«»"]/g, "").trim();
  const card = wanted ? (cards.find((c) => c.title.trim() === wanted)?.title || "") : "";
  if (behavior === "skip") reply = "";
  // reactivate: رقم أوردر بس (حروف/أرقام/شرطة) — وفي رد حقيقي للعميل بس (مش escalate ولا skip)
  const ra = String(o.reactivate ?? "").replace(/[#\s]/g, "").slice(0, 24);
  const reactivate = ra && /^[\p{L}\p{N}-]+$/u.test(ra) && behavior !== "escalate" && behavior !== "skip" ? ra : null;
  // fee (رسوم الإلغاء — 23 نوفمبر): القيم المعروفة بس، و«none» = مفيش · الحقل مش موجود = نفس شكل المسودة القديم بالحرف
  const fv = String(o.fee ?? "").trim();
  const fee = fv === "request" || fv === "paid" || fv === "refused" || fv === "keep" ? fv : null;
  return { behavior, intent: cut(String(o.intent ?? "").trim(), 80), reply, card, note: cut(String(o.note ?? "").trim(), 400), order: parseOrder(behavior, o.order), reactivate, ...(fee ? { fee } : {}) };
}

/** رقم واتساب (2010…) → الأشكال اللي ممكن يكون متخزّن بيها في orders.phone. [] لو مش موبايل مصري. */
export function phoneForms(waId: string): string[] {
  let d = latinDigits(String(waId || "")).replace(/\D/g, "");
  if (d.startsWith("0020")) d = d.slice(4);
  else if (d.startsWith("20") && d.length === 12) d = d.slice(2);
  if (d.length === 10 && d.startsWith("1")) d = "0" + d;
  if (!/^01[0-9]{9}$/.test(d)) return [];
  return [d, "2" + d, "+2" + d, d.slice(1)];
}
